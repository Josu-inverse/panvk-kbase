#!/bin/sh
# 0172: the BC1-BC5 -> ETC2/EAC transcoder once per mode at the default
# PANVK_BC_LM_OPTS (0x3020000), with spirv-opt -O folding away the other
# modes: the full shader costs the driver front end ~500 ms per mode on the
# X6 Pro, of which the back end is under 45 ms. Called by gen_spv.sh.
set -eu
cd "$(dirname "$0")"
t=$(mktemp -d)
out=panvk_bc_etc2_fixed_spv.h
{
   echo "/* Generated by gen_etc2_fixed.sh from panvk_bc_etc2.comp. */"
   echo "#pragma once"
} > $out
for m in 0 1 2 3 4 5 6 7; do
   glslangValidator -V --target-env vulkan1.1 -DXC_MODE_FIXED=${m}u \
      -DXC_OPTS_FIXED=0x3020000u -o $t/m.spv panvk_bc_etc2.comp > /dev/null
   spirv-opt -O $t/m.spv -o $t/o.spv
   {
      echo "static const uint32_t panvk_bc_etc2_m${m}_spv[] = {"
      od -An -v -tx4 -w32 $t/o.spv | sed -e 's/^ */\t0x/' -e 's/ \+/,0x/g' -e 's/$/,/'
      echo "};"
   } >> $out
done
for m in 8 9; do
   glslangValidator -V --target-env vulkan1.1 -DPANVK_BC_BLOCK -DXC_MODE_FIXED=${m}u \
      -o $t/m.spv panvk_bc_bc6.comp > /dev/null
   spirv-opt -O $t/m.spv -o $t/o.spv
   {
      echo "static const uint32_t panvk_bc_bc6_blk_m${m}_spv[] = {"
      od -An -v -tx4 -w32 $t/o.spv | sed -e 's/^ */\t0x/' -e 's/ \+/,0x/g' -e 's/$/,/'
      echo "};"
   } >> $out
done
rm -rf $t
