#define PANVK_BC_EAC_LUTGEN 1
#include "panvk_bc_eac_lut.h"

#include <stdio.h>

static unsigned
fit(const int pv[8], int kind)
{
   const int bmin = kind == 2 ? -127 : 0, bmax = kind == 2 ? 127 : 255;
   const int vmin = kind == 2 ? -1023 : 0;
   const int vmax = kind == 0 ? 255 : kind == 1 ? 2047 : 1023;
   const int sc = kind == 0 ? 1 : 8, c0 = kind == 1 ? 4 : 0;
   int lo = pv[0], hi = pv[0];

   for (int k = 1; k < 8; k++) {
      lo = pv[k] < lo ? pv[k] : lo;
      hi = pv[k] > hi ? pv[k] : hi;
   }
   const int need_lo = lo == vmin, need_hi = hi == vmax;

   long best = -1, best_any = -1;
   unsigned best_h = 0, best_any_h = 0;
   for (int t = 0; t < 16; t++) {
      for (int m = kind == 0 ? 1 : 0; m < 16; m++) {
         const int s = kind == 0 ? m : (m == 0 ? 1 : 8 * m);
         const float mid = 0.5f * (float)(panvk_bc_eac_mod[t][3] +
                                          panvk_bc_eac_mod[t][7]) * s;
         const int b0 = panvk_bc_eac_rnd(((lo + hi) * 0.5f - mid - c0) / sc);
         for (int b = b0 - 4; b <= b0 + 4; b++) {
            if (b < bmin || b > bmax)
               continue;
            const unsigned h = (unsigned)(b & 0xff) | (unsigned)(m << 4 | t) << 8;
            int lv[8];
            panvk_bc_eac_levels(h, kind, lv);
            int has_lo = 0, has_hi = 0;
            for (int j = 0; j < 8; j++) {
               has_lo |= lv[j] == vmin;
               has_hi |= lv[j] == vmax;
            }
            const int ok = (!need_lo || has_lo) && (!need_hi || has_hi);
            const long bound = ok ? best : best_any;
            long err = 0;
            for (int k = 0; k < 8 && (bound < 0 || err < bound); k++) {
               long e = -1;
               for (int j = 0; j < 8; j++) {
                  const long d = (long)(lv[j] - pv[k]) * (lv[j] - pv[k]);
                  e = e < 0 || d < e ? d : e;
               }
               err += e;
            }
            if (ok && (best < 0 || err < best)) {
               best = err;
               best_h = h;
            }
            if (!ok && (best_any < 0 || err < best_any)) {
               best_any = err;
               best_any_h = h;
            }
         }
      }
   }
   return best >= 0 ? best_h : best_any_h;
}

int
main(void)
{
   printf("/* Generated by panvk_bc_eac_lutgen.c (csf-v11/206), do not edit.\n"
          " * EAC header (base | (mult << 4 | table) << 8) per BC4 endpoint\n"
          " * pair key = e0 | e1 << 8, two keys per word (even key low). */\n"
          "static const uint32_t panvk_bc_eac_lut_hdr[%d][%d] = {\n",
          PANVK_BC_EAC_KINDS, PANVK_BC_EAC_KEYS / 2);
   for (int kind = 0; kind < PANVK_BC_EAC_KINDS; kind++) {
      printf("{\n");
      for (unsigned key = 0; key < PANVK_BC_EAC_KEYS; key += 2) {
         int pv[8];
         panvk_bc_eac_palette(key, kind, pv);
         const unsigned h0 = fit(pv, kind);
         panvk_bc_eac_palette(key + 1, kind, pv);
         const unsigned h1 = fit(pv, kind);
         printf("0x%x,%s", h0 | h1 << 16, (key & 14) == 14 ? "\n" : "");
      }
      printf("},\n");
      fflush(stdout);
   }
   printf("};\n");
   return 0;
}
